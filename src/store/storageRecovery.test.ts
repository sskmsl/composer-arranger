import { beforeEach, expect, it, vi } from "vitest"
import { createEmptyProject } from "@/core/project"
const storage = vi.hoisted(() => ({ saveProject: vi.fn(), loadLastOpenedProject: vi.fn(), loadProject: vi.fn(), putProjectRecord: vi.fn(), deleteProject: vi.fn() }))
vi.mock("@/storage/projectRepository", () => ({ ...storage,
  backupProjectTimingSnapshot: vi.fn(), duplicateProject: vi.fn(), renameProject: vi.fn(),
}))
beforeEach(() => { vi.resetModules(); storage.saveProject.mockReset().mockResolvedValue(undefined); storage.loadLastOpenedProject.mockReset(); storage.loadProject.mockReset(); storage.putProjectRecord.mockReset().mockResolvedValue(undefined); storage.deleteProject.mockReset().mockResolvedValue(undefined) })
it("exits startup loading on failure and recovers without writing empty data", async () => {
  storage.loadLastOpenedProject.mockRejectedValueOnce(new Error("blocked")).mockResolvedValueOnce(createEmptyProject("restored"))
  const { useProjectStore } = await import("./useProjectStore")
  await useProjectStore.getState().hydrate()
  expect(useProjectStore.getState()).toMatchObject({ hydrated: true, storageLoadError: true })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  expect(storage.saveProject).not.toHaveBeenCalled()
  await useProjectStore.getState().hydrate()
  expect(useProjectStore.getState().storageLoadError).toBe(false)
  expect(useProjectStore.getState().project.title).toBe("restored")
})
it("keeps edits available after a failed save and retries the latest snapshot", async () => {
  storage.saveProject.mockRejectedValueOnce(new Error("quota"))
  const { useProjectStore } = await import("./useProjectStore")
  const p = createEmptyProject("unsaved")
  useProjectStore.setState({ project: p })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  expect(useProjectStore.getState().saveStatus).toBe("error")
  expect(useProjectStore.getState().project).toBe(p)
  useProjectStore.setState({ project: { ...p, title: "newest" } })
  expect(await useProjectStore.getState().flushSave()).toBe(true)
  expect(storage.saveProject.mock.lastCall?.[0].title).toBe("newest")
  expect(useProjectStore.getState().saveStatus).toBe("saved")
})

it("reopens the latest unsaved edit instead of replacing it with an older DB record", async () => {
  storage.saveProject.mockRejectedValue(new Error("quota"))
  const { useProjectStore } = await import("./useProjectStore")
  const latest = createEmptyProject("latest unsaved")
  storage.loadProject.mockResolvedValue({ ...latest, title: "old DB version" })
  useProjectStore.setState({ project: latest })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  useProjectStore.setState({ project: createEmptyProject("other project") })
  await useProjectStore.getState().loadProjectById(latest.projectId)
  expect(useProjectStore.getState().project.title).toBe("latest unsaved")
  expect(storage.loadProject).not.toHaveBeenCalled()
})

it("preserves unsaved edits when hydration refreshes after synchronization", async () => {
  storage.saveProject.mockRejectedValue(new Error("quota"))
  const { useProjectStore } = await import("./useProjectStore")
  const latest = createEmptyProject("unsaved before sync refresh")
  storage.loadLastOpenedProject.mockResolvedValue({ ...latest, title: "old DB version" })
  useProjectStore.setState({ project: latest, hydrated: true })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  await useProjectStore.getState().hydrate()
  expect(useProjectStore.getState().project).toBe(latest)
  storage.saveProject.mockResolvedValue(undefined)
  expect(await useProjectStore.getState().flushSave()).toBe(true)
  expect(storage.saveProject.mock.lastCall?.[0].title).toBe(latest.title)
})

it("does not replace edits made while hydration is reading the database", async () => {
  const { useProjectStore } = await import("./useProjectStore")
  const initial = createEmptyProject("before read"), edited = { ...initial, title: "edited during read" }
  let finishRead!: (value: typeof initial) => void
  storage.loadLastOpenedProject.mockReturnValue(new Promise((resolve) => { finishRead = resolve }))
  useProjectStore.setState({ project: initial, hydrated: true })
  const reading = useProjectStore.getState().hydrate()
  useProjectStore.setState({ project: edited })
  // Even a successful save during the read must not permit the old read to replace the UI.
  expect(await useProjectStore.getState().flushSave()).toBe(true)
  finishRead(initial)
  await reading
  expect(useProjectStore.getState().project).toBe(edited)
})

it("keeps the failed latest edit when deleting the active project falls back to it", async () => {
  storage.saveProject.mockRejectedValue(new Error("quota"))
  const { useProjectStore } = await import("./useProjectStore")
  const a = createEmptyProject("latest A"), b = createEmptyProject("B")
  storage.loadLastOpenedProject.mockResolvedValue({ ...a, title: "old A in DB" })
  storage.loadProject.mockResolvedValue({ ...a, title: "old A in DB" })
  useProjectStore.setState({ project: a })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  useProjectStore.setState({ project: b })
  await useProjectStore.getState().deleteStoredProject(b.projectId)
  expect(useProjectStore.getState().project.title).toBe("latest A")
})
it("restores retained inactive edits if their deletion fails", async () => {
  storage.saveProject.mockRejectedValue(new Error("quota"))
  storage.deleteProject.mockRejectedValueOnce(new Error("delete aborted"))
  const { useProjectStore } = await import("./useProjectStore")
  const a = createEmptyProject("retained latest A"), b = createEmptyProject("active B")
  storage.loadProject.mockResolvedValue({ ...a, title: "old DB A" })
  useProjectStore.setState({ project: a })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  useProjectStore.setState({ project: b })
  await expect(useProjectStore.getState().deleteStoredProject(a.projectId)).rejects.toThrow("delete aborted")
  expect(useProjectStore.getState().project).toBe(b)
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  expect(useProjectStore.getState().saveStatus).toBe("error")
  await useProjectStore.getState().loadProjectById(a.projectId)
  expect(useProjectStore.getState().project.title).toBe("retained latest A")
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  storage.saveProject.mockResolvedValue(undefined)
  expect(await useProjectStore.getState().flushSave()).toBe(true)
  expect(storage.saveProject.mock.lastCall?.[0].title).toBe("retained latest A")
})
it("renames a retained inactive project without losing edits or changing lastOpened", async () => {
  storage.saveProject.mockRejectedValue(new Error("quota"))
  storage.putProjectRecord.mockRejectedValue(new Error("quota"))
  const { useProjectStore } = await import("./useProjectStore")
  const a = createEmptyProject("latest A"), b = createEmptyProject("active B")
  useProjectStore.setState({ project: a })
  expect(await useProjectStore.getState().flushSave()).toBe(false)
  useProjectStore.setState({ project: b })
  await useProjectStore.getState().renameStoredProject(a.projectId, "renamed A")
  expect(useProjectStore.getState().project).toBe(b)
  expect(storage.putProjectRecord.mock.lastCall?.[0]).toMatchObject({ projectId: a.projectId, title: "renamed A" })
  expect(storage.saveProject.mock.calls.some(([p]) => p.title === "renamed A")).toBe(false)
  await useProjectStore.getState().loadProjectById(a.projectId)
  expect(useProjectStore.getState().project.title).toBe("renamed A")
  storage.saveProject.mockResolvedValue(undefined)
  expect(await useProjectStore.getState().flushSave()).toBe(true)
  expect(storage.saveProject.mock.lastCall?.[0].title).toBe("renamed A")
})
